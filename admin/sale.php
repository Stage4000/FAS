require_once __DIR__ . '/auth.php';
require_once __DIR__ . '/../src/utils/CSRF.php';

use FAS\Utils\CSRF;

$auth = new AdminAuth();
$auth->requireLogin();

$success = '';
$error   = '';

$configFile = __DIR__ . '/../src/config/config.php';
$config     = file_exists($configFile) ? require $configFile : [];
$sale       = $config['sale'] ?? [
    'enabled'   => false,
    'type'      => 'percentage',
    'value'     => 0,
    'label'     => 'SALE',
    'starts_at' => '',
    'ends_at'   => '',
];

if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    if (!CSRF::validateToken($_POST['csrf_token'] ?? '')) {
        $error = 'Invalid security token. Please try again.';
    } else {
        $type  = in_array($_POST['type'] ?? '', ['percentage', 'fixed'], true)
                    ? $_POST['type']
                    : 'percentage';
        $value = max(0, (float) ($_POST['value'] ?? 0));

        // Clamp percentage to 0–99
        if ($type === 'percentage') {
            $value = min(99, $value);
        }

        $startsAt = !empty($_POST['starts_at']) ? $_POST['starts_at'] : null;
        $endsAt   = !empty($_POST['ends_at'])   ? $_POST['ends_at']   : null;

        // Validate datetime values
        if ($startsAt !== null && strtotime($startsAt) === false) {
            $error = 'Invalid "Starts At" date/time.';
        } elseif ($endsAt !== null && strtotime($endsAt) === false) {
            $error = 'Invalid "Ends At" date/time.';
        } else {

        $sale = [
            'enabled'   => isset($_POST['enabled']),
            'type'      => $type,
            'value'     => $value,
            'label'     => trim($_POST['label'] ?? 'SALE'),
            'starts_at' => $startsAt,
            'ends_at'   => $endsAt,
        ];

        // Read the current full config and replace only the 'sale' key
        $config['sale'] = $sale;

        $configContent = "<?php\n/**\n * Configuration File\n * Generated by Admin Panel\n */\n\nreturn " . var_export($config, true) . ";\n";

        if (file_put_contents($configFile, $configContent)) {
            $success = 'Sale settings saved successfully!';
        } else {
            $error = 'Failed to save settings. Check file permissions.';
        }
        } // end date validation
    }
}

// Determine whether the sale is currently live
$saleIsLive = false;
if (!empty($sale['enabled'])) {
    $now       = time();
    $startOk   = empty($sale['starts_at']) || (($ts = strtotime($sale['starts_at'])) !== false && $ts <= $now);
    $endOk     = empty($sale['ends_at'])   || (($ts = strtotime($sale['ends_at']))   !== false && $ts >= $now);
    $saleIsLive = $startOk && $endOk;
}
