    <script>
    function updatePreview() {
        var type  = document.getElementById('type').value;
        var value = parseFloat(document.getElementById('value').value) || 0;
        var base  = 100.00;

        document.getElementById('typeUnit').textContent =
            type === 'percentage' ? '(0–99, e.g. 20 for 20% off)' : '(e.g. 5 for $5 off)';

        var salePrice;
        if (type === 'percentage' && value > 0 && value < 100) {
            salePrice = Math.round(base * (1 - value / 100) * 100) / 100;
        } else if (type === 'fixed' && value > 0) {
            salePrice = Math.max(0.01, Math.round((base - value) * 100) / 100);
        } else {
            salePrice = null;
        }

        var priceEl    = document.getElementById('preview-price');
        var origEl     = document.getElementById('preview-original');
        var badgeEl    = document.getElementById('preview-badge');
        var badgeText  = document.getElementById('preview-badge-text');

        if (salePrice !== null && salePrice < base) {
            priceEl.textContent   = '$' + salePrice.toFixed(2);
            origEl.textContent    = '$' + base.toFixed(2);
            origEl.style.display  = 'inline';
            badgeEl.style.display = 'block';
            var pct = Math.round((base - salePrice) / base * 100);
            badgeText.textContent = 'Save ' + pct + '%';
        } else {
            priceEl.textContent   = '$' + base.toFixed(2);
            origEl.style.display  = 'none';
            badgeEl.style.display = 'none';
        }
    }
    document.addEventListener('DOMContentLoaded', updatePreview);
    </script>

