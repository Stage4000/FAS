            'product_flags_enabled' => isset($_POST['product_flags_enabled']),
            'auto_rules_enabled' => isset($_POST['auto_rules_enabled']),
            'max_weight' => fasShippingPositiveFloatOrNull($_POST['max_weight'] ?? null),
            'max_length' => fasShippingPositiveFloatOrNull($_POST['max_length'] ?? null),
