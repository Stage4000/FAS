function fasShippingPositiveFloatOrNull($value): ?float
{
    if ($value === null || $value === '') {
        return null;
    }

    $number = (float)$value;
    return $number > 0 ? $number : null;
}

function fasShippingSettingValue(array $settings, string $field): string
{
    return $settings[$field] !== null ? (string)$settings[$field] : '';
}

